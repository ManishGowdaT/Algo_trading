// Offline, deterministic acceptance evidence. Never connects to a broker or database.
const fs = require('node:fs');
const path = require('node:path');
const { candles, evaluate, replay } = require('../tests/helpers/indexOrbReplay');
const root = path.resolve(__dirname,'../..');
const evidence = [];
const overlays = [];
const check = process.argv.includes('--check');
function writeOrCheck(file, content) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file,'utf8') !== content) throw new Error(`Stale Phase 6 evidence: ${file}`);
  } else {fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content);}
}
for (const underlying of ['NIFTY','BANKNIFTY','SENSEX']) for(const direction of ['LONG','SHORT']) {
  for(const scenario of ['signal','no-breakout','no-retest','failed-retest','failed-vwap','missing-opening','zero-volume']) evidence.push(replay(underlying,direction,scenario));
  const bars = candles(direction);
  for(const count of [20,25,29,30,31]) overlays.push({ underlying,direction,count,date:'2026-10-16',candles:bars.slice(0,count),
    status:{isRunning:true,state:'SCANNING',analysis:evaluate(bars,count,underlying)} });
}
for (const session of evidence) {
  session.expectedEntries = session.scenario === 'signal' ? 1 : 0;
  session.actualEntries = session.trace.filter(row => row.signal).length;
  if (session.expectedEntries !== session.actualEntries) throw new Error(`Unexpected replay entry: ${session.underlying} ${session.direction} ${session.scenario}`);
}
const out = path.join(root,'output/phase6');
writeOrCheck(path.join(out,'replay-evidence.json'),JSON.stringify({
  source:'Synthetic OHLCV, not historical broker samples',sessionDate:'2026-10-16',
  assumptions:'One-minute HLC3 volume VWAP; full 375-bar sessions; 42 scenario/index/direction combinations. All prices and volumes fabricated for rule acceptance.',
  sessions:evidence,
},null,2)+'\n');
const fixture = path.join(root,'algo-trading/src/trading/fixtures/indexOrbPhase6Trace.ts');
writeOrCheck(fixture,'// Generated by backend/scripts/indexOrbPhase6Evidence.js from the production analyzer.\n// Synthetic sessions; no broker history or order fills.\nexport default '+JSON.stringify(overlays)+'\n');
console.log(`${check ? 'Verified' : 'Wrote'} ${evidence.length} replay traces and ${overlays.length} UI checkpoints.`);
